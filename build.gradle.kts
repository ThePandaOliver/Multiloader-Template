// Create build.properties file for pre-processor
fun createBuildProperties() {
	val builder = StringBuilder()
	builder.appendLine("# DON'T MODIFY THIS FILE!")
	builder.appendLine("# This file is automatically generated")
	builder.appendLine()

	val mcVersions: List<String> by extra
	val mcIndex: Int by extra

	mcVersions.forEachIndexed { index, version ->
		builder.appendLine("MC_${version.replace(".", "_")} = $index")
		if (index == mcIndex) builder.appendLine("MC_VER = $mcIndex")
	}

	File(rootDir, "build.properties").writeText(builder.toString())
}
